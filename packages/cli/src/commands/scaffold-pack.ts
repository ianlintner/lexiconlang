import { mkdir, writeFile } from "node:fs/promises";
import { resolve, join } from "node:path";
import { requireOption, type ParsedArgs } from "../args.js";

export async function runScaffoldPack(args: ParsedArgs): Promise<void> {
  const name = args.positional[0] ?? requireOption(args, "name");
  const outDir = (args.options["dir"] as string | undefined) ?? "./packages";
  const target = resolve(outDir, name);
  const safeName = name.replace(/[^a-z0-9-]/gi, "-").toLowerCase();
  const pkgName = `@lexiconlang/${safeName}`;
  const packId = `example.${safeName}`;
  const cultureId = `${packId}/culture/town`;
  const generatorId = `${packId}/generator/town-name`;

  await mkdir(join(target, "data"), { recursive: true });
  await mkdir(join(target, "src"), { recursive: true });

  const manifest = {
    $schema: "https://lexiconlang.dev/schemas/pack-v1.schema.json",
    formatVersion: 1,
    id: packId,
    version: "0.1.0",
    license: "CC0-1.0",
    description: `Original fictional names for ${safeName} (scaffold)`,
    provenance: [{
      id: "original",
      source: `original:${packId}`,
      title: `${safeName} example names`,
      creator: "Pack author",
      license: "CC0-1.0",
      attribution: "Original example data generated by lexiconlang scaffold-pack",
      modifications: "None",
      files: [`${safeName}.pack.json`],
    }],
    depends: [],
    extends: [],
    requires: ["language-v1"],
    cultures: [{
      id: cultureId,
      glyphs: { classes: { C: ["m", "n", "s"], V: ["a", "e", "i", "o", "u"] }, syllables: [["C V", 1]], wordShapes: [["2", 1]] },
      meaningPacks: [],
      templates: {
        given: [
          { value: { kind: "literal", form: "Mira", translation: "admired" }, weight: 1 },
          { value: { kind: "literal", form: "Talen", translation: "steadfast" }, weight: 1 },
        ],
      },
    }],
    meaningPacks: [],
    grammars: [],
    tables: [],
    corpora: [],
    markovModels: [],
    generators: [{
      id: generatorId,
      engine: "name-v1",
      culture: cultureId,
      kind: "given",
      description: `${safeName} given names`,
      tags: ["name", "given"],
      output: "translated-name-v1",
    }],
  };
  const json = JSON.stringify(manifest, null, 2) + "\n";

  await writeFile(join(target, "data", `${safeName}.pack.json`), json, "utf8");
  await writeFile(join(target, "PROVENANCE.md"), `# Provenance\n\nAll data in \`data/${safeName}.pack.json\` is original CC0-1.0 example content created by this scaffold.\n`, "utf8");
  await writeFile(join(target, "package.json"), JSON.stringify({
    name: pkgName,
    version: "0.1.0",
    type: "module",
    main: "./dist/src/index.js",
    types: "./dist/src/index.d.ts",
    exports: {
      ".": { types: "./dist/src/index.d.ts", import: "./dist/src/index.js" },
      "./pack.json": `./data/${safeName}.pack.json`,
    },
    files: ["dist", "data", "README.md", "PROVENANCE.md"],
    sideEffects: false,
    scripts: { build: "tsc -b", typecheck: "tsc --noEmit" },
    dependencies: { "@lexiconlang/packs": "workspace:*" },
  }, null, 2) + "\n", "utf8");
  await writeFile(join(target, "tsconfig.json"), JSON.stringify({
    extends: "../../tsconfig.base.json",
    compilerOptions: {
      outDir: "./dist",
      rootDir: ".",
      types: ["node"],
      paths: { "@lexiconlang/packs": ["../packs/src/index.ts"] },
    },
    include: ["src/**/*", "data/**/*.json"],
    exclude: ["src/**/*.test.ts", "dist"],
    references: [{ path: "../packs" }],
  }, null, 2) + "\n", "utf8");

  await writeFile(join(target, "src", "index.ts"), `import { definePack, createWorld } from "@lexiconlang/packs";
import packJson from "../data/${safeName}.pack.json" with { type: "json" };

/** Typed facade: JSON is the source of truth; this file only narrows its API. */
export const pack = definePack(packJson);
export const packId = pack.manifest.id;
export const generatorIds = pack.manifest.generators.map((g) => g.id);

export function createExampleWorld(seed: string) {
  return createWorld({ seed }).use(pack);
}
`, "utf8");
  await writeFile(join(target, "README.md"), `# ${pkgName}\n\nGenerated by \`lexiconlang scaffold-pack\`. The declarative source is \`data/${safeName}.pack.json\`; edit it and re-run \`lexiconlang validate-pack data/${safeName}.pack.json\`.\n\n\`\`\`ts\nimport { createExampleWorld, generatorIds } from "${pkgName}";\nconst name = createExampleWorld("my-seed").generate(generatorIds[0]!, "hero-1");\n\`\`\`\n`, "utf8");

  console.log(`[scaffold-pack] created ${pkgName} at ${target}`);
  console.log(`[scaffold-pack] validate with: lexiconlang validate-pack ${join(target, "data", `${safeName}.pack.json`)}`);
  console.log(`[scaffold-pack] add { "path": "./${name}" } to root tsconfig.json references, then run: pnpm install`);
}
